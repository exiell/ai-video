/** 按 id 找词条 */
export function findTerm(zh: string): Term | undefined {
  return TERMS.find((t) => t.zh === zh);
}

/** 按分类取词条 */
export function termsByCategory(category: TermCategory): Term[] {
  return TERMS.filter((t) => t.category === category);
}

/** 搜索：中文、英文、定义、用法都能命中 */
export function searchTerms(query: string): Term[] {
  const q = query.trim().toLowerCase();
  if (!q) return TERMS;
  return TERMS.filter((term) =>
    [term.zh, term.en, term.summary, term.whenToUse, term.example ?? '']
      .join(' ')
      .toLowerCase()
      .includes(q),
  );
}
